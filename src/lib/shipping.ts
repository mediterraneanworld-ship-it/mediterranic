export type ShippingMethodId = "standard" | "express";

export const SHIPPING_METHODS: {
  id: ShippingMethodId;
  label: string;
  detail: string;
}[] = [
  { id: "standard", label: "Insured standard", detail: "5–8 business days" },
  { id: "express", label: "Insured express", detail: "2–3 business days" },
];

const RATES: Record<ShippingZone, Record<ShippingMethodId, number>> = {
  americas: { standard: 3_900, express: 8_200 },
  europe: { standard: 5_400, express: 10_900 },
  asia: { standard: 6_000, express: 12_500 },
  rest: { standard: 7_500, express: 15_000 },
};

export function getCountry(code: string) {
  return COUNTRIES.find((c) => c.code === code);
}

/** Public labels for the three delivery zones, used on the Shipping & Returns page. */
export const ZONE_LABELS: Record<ShippingZone, string> = {
  europe: "Europe",
  americas: "Americas",
  asia: "Asia & Middle East",
  rest: "Rest of the world",
};

/** The order in which zones are presented to customers. */
export const ZONE_ORDER: ShippingZone[] = ["europe", "americas", "asia", "rest"];

/** Insured rates in cents for a zone — the same numbers the checkout charges. */
export function getZoneRates(zone: ShippingZone): Record<ShippingMethodId, number> {
  return RATES[zone];
}

/** Country names served in a zone, for the delivery table. */
export function countriesInZone(zone: ShippingZone): string[] {
  return COUNTRIES.filter((c) => c.zone === zone).map((c) => c.name);
}

/** Returns shipping in cents, or null when the country / method is unknown. */
export function calculateShipping(
  countryCode: string,
  method: ShippingMethodId,
  subtotalCents: number,
): number | null {
  const country = getCountry(countryCode);
  if (!country) return null;
  if (method === "standard" && subtotalCents >= FREE_SHIPPING_THRESHOLD_CENTS) return 0;
  return RATES[country.zone][method];
}
